import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {parseEnv} from 'node:util';
const env=parseEnv(readFileSync('.env','utf8'));
const base=process.env.TEST_URL||'http://127.0.0.1:8816';
test('delete bank requires confirmation, hides bank and preserves existing game',async({browser})=>{
 const context=await browser.newContext({extraHTTPHeaders:{Origin:base,...(base.includes('127.0.0.1')?{'x-origin-secret':env.ORIGIN_SECRET!}:{})}});
 const page=await context.newPage();
 await page.goto(base+'/admin');
 await page.getByLabel('Email',{exact:true}).fill(process.env.TEST_EMAIL||env.TEST_EMAIL!);await page.getByLabel('密碼',{exact:true}).fill(process.env.TEST_PASSWORD||env.TEST_PASSWORD!);
 await page.getByRole('button',{name:'登入',exact:true}).click();
 await expect(page.getByRole('button',{name:'登出',exact:true})).toBeVisible();
 const bankResponse=await context.request.post(base+'/api/banks',{data:{name:'刪除驗證 '+Date.now(),reference:'John 3:16'}});
 expect(bankResponse.ok()).toBeTruthy();const bank=await bankResponse.json();
 const gameResponse=await context.request.post(base+'/api/games',{data:{bankId:bank.id,teams:['刪除驗證','Delete verification'],innings:1,timers:[15,15,30,45]}});
 expect(gameResponse.ok()).toBeTruthy();let game=await gameResponse.json();
 const end=await context.request.post(base+`/api/games/${game.id}/action`,{data:{action:'end',version:game.version}});expect(end.ok()).toBeTruthy();
 await page.reload();await page.getByLabel('經文與題庫',{exact:true}).selectOption(bank.id);
 page.once('dialog',dialog=>dialog.dismiss());await page.getByRole('button',{name:'刪除題庫',exact:true}).click();
 await expect(page.getByLabel('經文與題庫',{exact:true})).toHaveValue(bank.id);
 await page.getByLabel('Language').selectOption('en');
 await expect(page.getByRole('button',{name:'Delete bank',exact:true})).toBeVisible();
 page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Delete bank',exact:true}).click();
 await expect(page.locator(`option[value="${bank.id}"]`)).toHaveCount(0);
 const dashboard=await (await context.request.get(base+'/api/dashboard')).json();expect(dashboard.banks.some((b:any)=>b.id===bank.id)).toBeFalsy();
 expect((await context.request.get(base+`/api/games/${game.id}`)).ok()).toBeTruthy();
 const recreate=await context.request.post(base+'/api/games',{data:{bankId:bank.id,teams:['A','B'],innings:1,timers:[15,15,30,45]}});expect(recreate.ok()).toBeFalsy();
 const repeat=await context.request.post(base+`/api/banks/${bank.id}/delete`,{data:{}});expect(repeat.status()).toBe(404);
 await context.close();
 const anonymous=await browser.newContext({extraHTTPHeaders:{Origin:base}});expect((await anonymous.request.post(base+`/api/banks/${bank.id}/delete`,{data:{}})).status()).toBe(401);await anonymous.close();
});
